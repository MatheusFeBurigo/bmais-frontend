export type Acesso = keyof typeof ACESSOS

export interface Endpoint {
  metodo: Metodo
  rota: string
  acesso: Acesso
  descricao: string
  /** Parâmetros de query, na ordem em que a rota os declara. */
  query?: string
  /** Corpo esperado: o schema (interface/schemas.py) e os campos que importam. */
  corpo?: string
}

