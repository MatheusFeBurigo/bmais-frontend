// Catálogo das APIs do backend, base da "Documentação técnica" (subrota de
// Progresso). É um levantamento sobre o código, não uma fonte de verdade: quem
// decide quem alcança cada rota é o servidor (interface/authz.py), e a lista
// viva de rotas é a do próprio FastAPI.
//
// Como foi levantado (26/10/2026): as rotas saíram do `router` de cada módulo
// em `bmais-backend/src/interface/routes/` (o `app.routes` do FastAPI 0.143 as
// esconde dentro de `_IncludedRouter`), e o guard efetivo de cada uma é a
// interseção do guard do router com o da rota, resolvida pela mesma tabela de
// `scripts/matriz_acessos.py`. Ao criar ou mudar uma rota, atualize aqui.
//
// O guard fica como CHAVE (e não como lista de papéis repetida em cada linha):
// a mesma regra vale para dezenas de rotas, e é ela que muda quando um papel
// entra ou sai — editar ACESSOS repinta todas as linhas de uma vez.
import type { UserRole } from '../../types/api'

export type Metodo = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'

